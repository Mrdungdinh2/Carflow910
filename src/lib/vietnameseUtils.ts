export function fixVietnameseUnicode(str: string | undefined | null): string {
  if (!str) return '';
  let s = String(str);

  // 1. Initial NFC normalization
  s = s.normalize('NFC');

  // 2. Replace known decomposed tone mark patterns
  for (const [pattern, replacement] of Object.entries(VIETNAMESE_UNICODE_MAP)) {
    if (s.includes(pattern)) {
      s = s.split(pattern).join(replacement);
    }
  }

  // 3. Re-normalize to NFC
  s = s.normalize('NFC');

  // 4. Remove any remaining orphan combining diacritical marks (U+0300 - U+036F)
  s = s.replace(/[\u0300-\u036F]/g, '');

  return s;
}
